#!/usr/bin/env bash
# install-scanners.sh — install the pinned scanner toolchain.
# Used identically by lab/Dockerfile (Rocky 9) and GitHub Actions (ubuntu-24.04),
# which is what makes a finding reproduce in both places.
#
#   install-scanners.sh --prefix /opt/scanners [--only gitleaks,trivy,...]
#
# Every archive is verified against the SHA-256 committed in versions.env
# before it is extracted. A mismatch or a missing pin fails closed.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
VERSIONS="${VERSIONS_FILE:-$HERE/../versions.env}"
[[ -f "$VERSIONS" ]] || VERSIONS=/opt/lab/versions.env
# shellcheck source=/dev/null
source "$VERSIONS"

PREFIX=/opt/scanners; ONLY="gitleaks,trivy,grype,syft,semgrep,checkov"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --prefix) PREFIX="$2"; shift 2 ;;
    --only)   ONLY="$2";   shift 2 ;;
    *) echo "unknown arg $1" >&2; exit 2 ;;
  esac
done
[[ "$(uname -m)" == "x86_64" ]] || { echo "amd64 only (lab hardware is x86_64)" >&2; exit 1; }
mkdir -p "$PREFIX/bin"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
want() { [[ ",$ONLY," == *",$1,"* ]]; }
need() { [[ -n "${!1:-}" ]] || { echo "versions.env: $1 is empty (run scripts/resolve-versions.sh)" >&2; exit 1; }; }

fetch_verify_extract() { # name url sha256 binary
  local name=$1 url=$2 sha=$3 bin=$4
  curl -fsSL --retry 3 -o "$WORK/$name.tgz" "$url"
  echo "$sha  $WORK/$name.tgz" | sha256sum -c --quiet - \
    || { echo "CHECKSUM MISMATCH for $name — refusing to install" >&2; exit 1; }
  tar -xzf "$WORK/$name.tgz" -C "$WORK" "$bin"
  install -m 0755 "$WORK/$bin" "$PREFIX/bin/$bin"
  echo "installed $bin from $url (sha256 $sha)"
}

if want gitleaks; then need GITLEAKS_VERSION; need GITLEAKS_SHA256
  fetch_verify_extract gitleaks \
    "https://github.com/gitleaks/gitleaks/releases/download/v${GITLEAKS_VERSION}/gitleaks_${GITLEAKS_VERSION}_linux_x64.tar.gz" \
    "$GITLEAKS_SHA256" gitleaks; fi

if want trivy; then need TRIVY_VERSION; need TRIVY_SHA256
  case "$TRIVY_VERSION" in 0.69.4|0.69.5|0.69.6) echo "Blocked Trivy release (CVE-2026-33634)" >&2; exit 1;; esac
  fetch_verify_extract trivy \
    "https://github.com/aquasecurity/trivy/releases/download/v${TRIVY_VERSION}/trivy_${TRIVY_VERSION}_Linux-64bit.tar.gz" \
    "$TRIVY_SHA256" trivy; fi

if want grype; then need GRYPE_VERSION; need GRYPE_SHA256
  fetch_verify_extract grype \
    "https://github.com/anchore/grype/releases/download/v${GRYPE_VERSION}/grype_${GRYPE_VERSION}_linux_amd64.tar.gz" \
    "$GRYPE_SHA256" grype; fi

if want syft; then need SYFT_VERSION; need SYFT_SHA256
  fetch_verify_extract syft \
    "https://github.com/anchore/syft/releases/download/v${SYFT_VERSION}/syft_${SYFT_VERSION}_linux_amd64.tar.gz" \
    "$SYFT_SHA256" syft; fi

if want semgrep || want checkov; then
  PY="${PYTHON:-$(command -v python3.12 || command -v python3)}"
  "$PY" -m venv "$PREFIX/venv"
  pkgs=(); want semgrep && { need SEMGREP_VERSION; pkgs+=("semgrep==${SEMGREP_VERSION}"); }
  want checkov && { need CHECKOV_VERSION; pkgs+=("checkov==${CHECKOV_VERSION}"); }
  # Hardening option: replace with `pip install --require-hashes -r scanners.lock`
  # generated by `pip-compile --generate-hashes`.
  "$PREFIX/venv/bin/pip" install --no-cache-dir --disable-pip-version-check "${pkgs[@]}"
  for b in semgrep pysemgrep checkov; do
    [[ -x "$PREFIX/venv/bin/$b" ]] && ln -sf "$PREFIX/venv/bin/$b" "$PREFIX/bin/$b"
  done
fi

"$PREFIX/bin/gitleaks" version 2>/dev/null || true
echo "toolchain ready in $PREFIX/bin"
